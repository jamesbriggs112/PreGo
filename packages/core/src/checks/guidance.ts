const GENERIC_WHY =
  'This makes the interface harder or impossible to use for some people, including those using screen readers, keyboards or magnification.';

export function guidanceFor(engine: string, ruleId: string): RuleGuidance | undefined {
  if (engine === 'axe-core') return AXE[ruleId];
  if (engine === 'prego') return PREGO[ruleId];
  if (engine === 'retire.js') return PREGO[ruleId];
  return undefined;
}

/** Guidance with fallbacks for rules that have no plain-English entry yet. */
/** Why-it-matters text for engines whose rules have no plain-English entry of their own. */
const GENERIC_WHY_BY_ENGINE: Record<string, string> = {
  'html-validate': 'Invalid markup is repaired differently by each browser and by assistive technology, so the page can look or behave differently from what was intended.',
  lighthouse: 'Slow, fragile or badly indexed pages lose visitors, cost more to run on mobile data and rank lower in search results.',
};

export function guidanceWithFallback(
  engine: string,
  ruleId: string,
  fallback: { title: string; description: string; helpUrl: string | null },
): RuleGuidance {
  const guidance = guidanceFor(engine, ruleId);
  // Each outdated library, misspelt word and browser gets its own ticket, so the title names it.
  if (guidance && (engine === 'retire.js' || ruleId === 'spelling' || ruleId.startsWith('browser-'))) return { ...guidance, title: fallback.title };
  if (engine === 'ollama') {
    return {
      title: fallback.title,
      description: fallback.description,
      whyItMatters: 'Usability problems like this make the product harder to learn and use, and cause mistakes and drop-off. This is a suggestion from a local AI model, so check it on the screen before acting on it.',
      recommendation: 'Confirm the problem on the screen. If it’s real, approve the ticket and follow the suggested fix in “Actual”; if not, dismiss it.',
      effort: 'Medium',
    };
  }
  return (
    guidance ?? {
      title: fallback.title,
      description: fallback.description,
      whyItMatters: GENERIC_WHY_BY_ENGINE[engine] ?? GENERIC_WHY,
      recommendation: fallback.helpUrl ? `Follow the guidance at ${fallback.helpUrl}.` : 'Review and fix the affected elements.',
      effort: 'Medium',
    }
  );
}
