/** IBM wording for a rule: its title, fuller wording where there is some, and why it matters by WCAG criterion. */
export function ibmGuidance(ruleId: string, criteria: string[] = []): RuleGuidance | undefined {
  const title = IBM_TITLES[ruleId];
  if (!title) return undefined;
  const detail = IBM_DETAIL[ruleId];
  const why = criteria.map((c) => WHY_BY_CRITERION[c]).find(Boolean);
  return {
    title,
    description: detail?.description ?? `${title}. Found by IBM Equal Access, the second accessibility checker.`,
    whyItMatters: why ?? 'It makes the page harder or impossible to use for people with disabilities.',
    recommendation: detail?.recommendation ?? `See IBM’s explanation of the “${ruleId}” rule (linked from the ticket) for how to fix it.`,
    effort: detail?.effort ?? 'Small',
  };
}
